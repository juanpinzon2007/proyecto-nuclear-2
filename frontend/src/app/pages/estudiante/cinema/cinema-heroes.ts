export const HEROES_POR_TEMA: Record<TemaEscena, HeroeId[]> = {
  tribunal_comite: ['captain_america', 'batman', 'superman', 'daredevil'],
  laboratorio_autoridad: ['iron_man', 'doctor_strange', 'flash', 'cyborg'],
  hospital_urgencias: ['spider_man', 'green_lantern', 'wonder_woman', 'black_panther'],
  entrevista_clinica: ['wonder_woman', 'doctor_strange', 'spider_man', 'superman'],
  proteccion_riesgo: ['black_panther', 'green_lantern', 'captain_america', 'batman'],
  red_ciudad: ['doctor_strange', 'cyborg', 'iron_man', 'flash'],
};

export function elegirHeroeAleatorio(
  tema: TemaEscena,
  excluirId?: HeroeId,
  rng: () => number = Math.random,
): PerfilHeroe {
  const candidatos = HEROES_POR_TEMA[tema] ?? HEROES_POR_TEMA.red_ciudad;
  const filtrados = excluirId && candidatos.length > 1 ? candidatos.filter((id) => id !== excluirId) : candidatos;
  const indice = Math.min(filtrados.length - 1, Math.floor(rng() * filtrados.length));
  return CATALOGO_HEROES[filtrados[Math.max(0, indice)]];
}
